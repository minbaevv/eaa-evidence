def get_strings(lang: str) -> dict[str, str]:
    if lang not in SUPPORTED_LANGS:
        lang = DEFAULT_LANG
    fallback = STRINGS[DEFAULT_LANG]
    merged = dict(fallback)
    merged.update(STRINGS[lang])
    return merged


def resolve_lang(request: Any) -> str:
    """Query param (?lang=ru) > cookie > browser Accept-Language > default."""
    wanted = (request.query_params.get("lang") or "").lower()[:2]
    if wanted in SUPPORTED_LANGS:
        return wanted
    cookie = (request.cookies.get("eaa_lang") or "").lower()[:2]
    if cookie in SUPPORTED_LANGS:
        return cookie
    accept = (request.headers.get("accept-language") or "").lower()
    if "ru" in accept:
        return "ru"
    return DEFAULT_LANG


def plural(lang: str, n: int, one: str, few: str, many: str) -> str:
    """Russian-grade pluralization; English collapses to one/many."""
    if lang == "ru":
        if n % 10 == 1 and n % 100 != 11:
            return one
        if 2 <= n % 10 <= 4 and not (12 <= n % 100 <= 14):
            return few or many
        return many
    return one if n == 1 else many
